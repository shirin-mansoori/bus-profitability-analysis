------------------------------------------------Inserting data with corrected data types------------------------------
INSERT INTO bus_daily_records
SELECT
	COALESCE(
		TRY_CONVERT(DATE, [DATE], 103),
		TRY_CONVERT(DATE, [DATE],5)
	) AS [DATE],
    TRY_CONVERT(DECIMAL(10,2), NULLIF(UJJAIN_DEP, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(UNHEL_DEP, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(NAGDA_DEP, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(KHACHROD_DEP, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(JAORA, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(KHACHROD, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(NAGDA, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(UNHEL, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(BADNAGAR, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(LUGGAGE, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(DIESEL, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(MAINTENANCE, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(LABOUR, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(COLLECTED, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(OTHER_EXPENSES, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(PASSENGER_REVENUE, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(GROSS_INCOME, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(TOTAL_EXPENSES, '')),
    TRY_CONVERT(DECIMAL(10,2), NULLIF(NET_INCOME, '')),
