	LABOUR DECIMAL(10,2),
	COLLECTED DECIMAL(10,2),
	OTHER_EXPENSES DECIMAL(10,2),
	PASSENGER_REVENUE DECIMAL(10,2),
	GROSS_INCOME DECIMAL(10,2),
